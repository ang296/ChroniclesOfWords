        seeds.mapIndexed { itemIndex, seed ->
            val options = when ((levelIndex + itemIndex) % 3) {
                0 -> listOf(seed.word, seed.wrong1, seed.wrong2)
                1 -> listOf(seed.wrong1, seed.word, seed.wrong2)
                else -> listOf(seed.wrong2, seed.wrong1, seed.word)
            }
            Exercise(
                id = "doubling-${levelIndex + 1}-${itemIndex + 1}",
                topic = "Подвоєння приголосних",
                prompt = prompts[levelIndex],
                options = options,
                correctIndex = options.indexOf(seed.word),
                explanation = seed.explanation,
                paragraph = "Подвоєння приголосних: подовження та збіг на межі морфем",
                missionLevel = levelIndex + 1
