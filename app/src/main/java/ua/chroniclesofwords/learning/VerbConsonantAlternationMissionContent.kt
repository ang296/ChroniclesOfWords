                id = "verb-consonant-alternation-${levelIndex + 1}-${itemIndex + 1}",
                topic = "Чергування приголосних у дієсловах",
                prompt = "${levels[levelIndex]}: ${seed.prompt}",
                options = options,
                correctIndex = options.indexOf(seed.answer),
                explanation = seed.explanation,
                paragraph = "Чергування приголосних у дієсловах",
