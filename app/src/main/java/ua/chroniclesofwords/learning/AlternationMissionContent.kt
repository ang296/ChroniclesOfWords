        "Рівень I · Базове розпізнавання",
        "Рівень II · Чергування під час словотворення",
        "Рівень III · Чергування приголосних",
        "Рівень IV · Граматичні форми та дієвідмінювання",
        "Рівень V · Комплексне випробування"
    )

    val exercises: List<Exercise> = missions.flatMapIndexed { levelIndex, seeds ->
        seeds.mapIndexed { itemIndex, seed ->
            val options = when ((levelIndex + itemIndex) % 3) {
                0 -> listOf(seed.answer, seed.wrong1, seed.wrong2)
                1 -> listOf(seed.wrong1, seed.answer, seed.wrong2)
                else -> listOf(seed.wrong2, seed.wrong1, seed.answer)
            }
            Exercise(
                id = "alternation-${levelIndex + 1}-${itemIndex + 1}",
                topic = "Чергування голосних і приголосних",
                prompt = "${prompts[levelIndex]}: ${seed.prompt}",
                options = options,
                correctIndex = options.indexOf(seed.answer),
                explanation = seed.explanation,
                paragraph = "Чергування голосних і приголосних",
                missionLevel = levelIndex + 1
            )
        }
